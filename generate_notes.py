from PIL import Image, ImageDraw
import os

CELL = 10
SIZE = 100
N    = SIZE // CELL

C1 = (0xd6, 0x72, 0xcc, 255)   # primary pink
C2 = (0x78, 0x58, 0x6f, 255)   # shadow mauve
T  = (0, 0, 0, 0)              # transparent

def draw_note(grid, path):
    img  = Image.new('RGBA', (SIZE, SIZE), T)
    draw = ImageDraw.Draw(img)
    for r in range(N):
        for c in range(N):
            v = grid[r][c]
            if v == 0:
                continue
            x0, y0 = c * CELL, r * CELL
            color = C1 if v == 1 else C2
            # 8x8 main fill + 2px bevel on right and bottom
            draw.rectangle([x0,   y0,   x0+7, y0+7], fill=color)
            draw.rectangle([x0+8, y0,   x0+9, y0+9], fill=C2)
            draw.rectangle([x0,   y0+8, x0+9, y0+9], fill=C2)
    img.save(path)

